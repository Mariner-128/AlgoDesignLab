# ==================== 10-2 随机快速排序与随机选择 ====================
t102 = """## 随机化快速排序

普通快排固定取某位置作主元, 有序输入退化为 O(n²)。**随机化快排**每次**均匀随机**选主元:

```text
randomized_quicksort(A, lo, hi):
    若 lo >= hi 返回
    r = random(lo, hi); 交换 A[r] 与 A[hi]
    p = partition(A, lo, hi)
    randomized_quicksort(A, lo, p-1); randomized_quicksort(A, p+1, hi)
```

**期望 O(n log n) 证明(指示变量)**: 设 X~ij~ = 1 表示第 i 小与第 j 小元素(i 小于 j)在排序过程中被比较。两元素被比较, 当且仅当在 {i, i+1, …, j} 中, **第一个被选为主元的是 i 或 j**——因为一旦中间元素先成主元, i、j 被分到两侧, 永不再比较。随机主元下该概率 = 2/(j−i+1)。由期望线性性(无需独立性):

> E[比较数] = Σ~i=1..n~ Σ~j=i+1..n~ 2/(j−i+1) = Σ~k=2..n~ 2(n−k+1)/k ≤ 2n·H~n~ = O(n log n)

划分正确 ⇒ 结果必对, 所以随机化快排是**拉斯维加斯**算法。

## 随机化选择(quickselect)

求第 k 小: 随机主元划分后, **只递归进入包含第 k 小的一侧**。期望时间 **O(n)**: 划分 O(n), 递归规模以概率 ≥ 1/2 不超过 3n/4, 得 E[T(n)] ≤ T(3n/4) + O(n) = O(n)(更精确的 ≤ 4n 见练习)。最坏仍 O(n²), 但概率指数级小。

## 与确定性版本对比

确定性快排的坏输入可被**精确构造**; 随机化后, 对**任意固定输入**, 坏情况概率 ≤ 1/n 量级——「坏输入」变成「坏运气」, 攻击者无法预知主元。确定性线性选择(中位数的中位数)常数大、难实现, 实践中随机化版本更常用。

**易错点**: partition 返回后主元已就位; quickselect 的 k 从 1 计; 期望分析依赖「主元均匀随机」; 不要对已排序数据用固定主元。"""

c102 = r"""#include <stdio.h>
#include <stdlib.h>
#include <time.h>

/* 随机化快速排序: 随机主元, 期望 O(n log n), 结果必然正确(拉斯维加斯) */
void swap(int *a, int *b) { int t = *a; *a = *b; *b = t; }

int rand_range(int lo, int hi) {              /* [lo, hi] 均匀随机(双 rand 扩到 30 位) */
    return lo + (int)(((unsigned long long)rand() * (RAND_MAX + 1ULL) + rand()) % (hi - lo + 1ULL));
}

int partition(int A[], int lo, int hi) {      /* Lomuto 划分: 以 A[hi] 为基准 */
    int pivot = A[hi], i = lo - 1;
    for (int j = lo; j < hi; j++)
        if (A[j] < pivot) { i++; swap(&A[i], &A[j]); }
    swap(&A[i + 1], &A[hi]);
    return i + 1;
}

void qsort_rand(int A[], int n) {
    /* 用显式栈模拟递归, 避免最坏情况深递归爆栈 */
    int *lo = (int *)malloc(sizeof(int) * (n + 5));
    int *hi = (int *)malloc(sizeof(int) * (n + 5));
    int top = 0;
    lo[top] = 0; hi[top] = n - 1; top++;
    while (top > 0) {
        top--;
        int l = lo[top], r = hi[top];
        if (l >= r) continue;
        int pv = rand_range(l, r);            /* 随机主元下标 */
        swap(&A[pv], &A[r]);
        int p = partition(A, l, r);
        lo[top] = l;     hi[top] = p - 1; top++;
        lo[top] = p + 1; hi[top] = r;     top++;
    }
    free(lo); free(hi);
}

int main(void) {
    int n, A[100005];
    printf("请输入元素个数 n: ");
    if (scanf("%d", &n) != 1 || n < 1 || n > 100000) { printf("输入无效!\n"); return 1; }
    printf("请输入 %d 个整数: ", n);
    for (int i = 0; i < n; i++) scanf("%d", &A[i]);
    srand((unsigned)time(NULL));              /* 随机种子: 每次运行主元序列不同 */
    qsort_rand(A, n);
    printf("排序结果: ");
    for (int i = 0; i < n; i++) printf("%d ", A[i]);
    printf("\n");
    return 0;
}
"""

