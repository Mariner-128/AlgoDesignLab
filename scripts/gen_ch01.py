# ==================== 1-2 复杂度分析 ====================
t12 = """## 如何度量运行时间

运行时间不能直接用"秒"衡量——同一算法在不同机器、不同语言实现下耗时不同。科学的方法是度量**基本操作(基本语句)的执行次数**, 记为关于输入规模 n 的函数 T(n)。基本操作指赋值、比较、算术等单条语句。

## 输入规模

输入规模是问题大小的量化, 必须随问题而定: 排序问题中是元素个数 n; 图问题中是顶点数 n 与边数 m; 矩阵乘法中是矩阵阶数 n; 数论问题中则是整数的**二进制位数** log n。分析时需说明以何为规模单位, 否则复杂度无意义。

## 最坏 / 平均 / 最好情况

同一算法对相同规模的**不同输入**, 运行时间可能不同:

- **最坏情况**: 所有输入中运行时间的最大值——给出算法性能的**保证**, 是默认指标;
- **平均情况**: 按输入的概率分布求期望时间(如快速排序平均 Θ(n log n), 见第 2 章);
- **最好情况**: 运行时间的最小值(如插入排序最好 Θ(n)), 一般不作性能依据。

## 常见增长阶

按增长速度从慢到快: Θ(1) ≺ Θ(log n) ≺ Θ(√n) ≺ Θ(n) ≺ Θ(n log n) ≺ Θ(n²) ≺ Θ(n³) ≺ Θ(2ⁿ) ≺ Θ(n!)。

- Θ(log n): 二分查找、平衡树操作;
- Θ(n): 线性扫描、Kadane 算法;
- Θ(n log n): 归并/快速/堆排序, 也是**基于比较的排序下界**;
- Θ(n²): 简单两重循环(选择/冒泡排序、Floyd-Warshall);
- Θ(2ⁿ): 指数级——n = 40 时 2⁴⁰ ≈ 10¹², 常规计算已不可行, 只能用于极小规模。

## 实例: 分析嵌套循环

对三重循环 `for i in 1..n: for j in 1..n: for k in 1..n: S`, 语句 S 执行 n³ 次, T(n) = Θ(n³)。若把最内层改为 `for k in 1..j`, 则执行次数 Σ~i~ Σ~j~ j = Σ~i~ n(n+1)/2 = Θ(n³) 不变; 若约束 i ≤ j ≤ k, 则次数为组合数 C(n+2, 3) = Θ(n³)。若循环为 `for i: for j in i..n`, 次数 Σ~i~ (n−i+1) = n(n+1)/2 = **Θ(n²)**——注意首项系数 1/2 被 Θ 吸收。

## 空间复杂度

空间复杂度 S(n) 度量算法运行所需的**额外**存储(不含输入本身)。原地(in-place)算法的额外空间为 O(1); 递归算法的隐式空间包括调用栈深度(如快速排序平均 O(log n)、归并排序合并时需要 O(n) 辅助数组)。空间与时间往往可以权衡(如用哈希表换时间)。

## 斐波那契的教训

朴素递归求 F(n) 满足 T(n) = T(n−1) + T(n−2) + Θ(1), 解为 **Θ(2ⁿ)**(指数爆炸); 而迭代法(自底向上)为 Θ(n)。本节的案例代码用计时实验直观展示这一差异——这是"为什么要学算法分析"最生动的例子。
"""

